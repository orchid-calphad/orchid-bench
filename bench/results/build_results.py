#!/usr/bin/env python3
"""Collect outputs/<extractor>/scores.json into results/results.json and results/RESULTS.md (task x rendering)."""
import json
import sys
from pathlib import Path

B = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(B))
from common import load_json, write_json  # noqa: E402

R = ["vector", "clean_raster", "degraded_raster", "image_only_pdf"]
RN = {"vector": "vector PDF", "clean_raster": "clean raster 300 dpi", "degraded_raster": "degraded raster 150 dpi",
      "image_only_pdf": "image-only PDF"}
NOT_RUN = {
    "tables": {"clean_raster": "not run: `thermo_extractor.tables.ocr` (ocr_table_cells) needs OpenCV; Camelot not installed",
               "degraded_raster": "not run: as clean raster", "image_only_pdf": "not run: no text layer; OCR table route needs OpenCV"},
    "phase_diagram": {r_: "not run: the vector route needs PDF vector objects (see assessed_pd for rasters)"
                      for r_ in ("clean_raster", "degraded_raster", "image_only_pdf")},
    "xy": {"clean_raster": "not run: multipanel raster marker proposals (`proposals/multipanel_markers.py`) need OpenCV",
           "degraded_raster": "not run: as clean raster", "image_only_pdf": "not run: vector route needs PDF vector objects; raster route needs OpenCV"},
}
TASKS = [
    ("tables", "tables_pdfplumber", ["tables_true", "tables_pred", "cells", "cell_exact", "cell_exact_normalised", "numeric_exact"]),
    ("xy", "vector_route", ["panels_true", "panels_found", "point_recall@0.01", "marker_recall@0.01", "point_err_median",
                            "series_recall", "series_precision"]),
    ("xy", "vector_markers_tool", ["panels_true", "panels_found", "marker_recall@0.01", "point_err_median", "series_recall",
                                   "series_precision"]),
    ("phase_diagram", "vector_route", ["diagrams_with_output", "boundary_precision@0.01", "boundary_recall@0.01",
                                       "boundary_hausdorff95", "boundary_median_dx", "boundary_median_dT_K", "field_precision",
                                       "field_recall", "invariant_recall", "invariant_precision", "invariant_T_err_K",
                                       "invariant_type_accuracy"]),
    ("phase_diagram", "assessed_pd", ["diagrams_with_output", "boundary_precision@0.01", "boundary_recall@0.01",
                                      "boundary_hausdorff95", "boundary_median_dx", "boundary_median_dT_K", "field_precision",
                                      "field_recall", "invariant_recall", "invariant_precision", "invariant_T_err_K",
                                      "invariant_type_accuracy"]),
    ("text", "text_regex", ["values_true", "values_pred", "precision", "recall", "value_only_recall"]),
]


def f(v):
    if v is None:
        return "–"
    if isinstance(v, float) and 0 < abs(v) < 0.001:
        return f"{v:.1e}"
    if isinstance(v, float):
        return f"{v:.3f}" if abs(v) < 100 else f"{v:.1f}"
    return str(v)


def main():
    res = {"tasks": [], "extractor_status": {}}
    md = ["# Baseline results", "",
          "Generated by `bench/results/build_results.py` from `bench/outputs/*/scores.json`. "
          "No model or API calls. Distances are in axis-normalised units (axis range = 1); `@0.01` = within 1 % of "
          "the axis range. `–` = not applicable or nothing to score.", ""]
    oracle = load_json(B / "outputs" / "oracle" / "scores.json")["aggregate"]
    for task, ext, keys in TASKS:
        p = B / "outputs" / ext / "scores.json"
        agg = load_json(p)["aggregate"] if p.exists() else {}
        row = {"task": task, "extractor": ext, "by_rendering": {}}
        md += [f"## {task} — `{ext}`", "", "| metric | " + " | ".join(RN[r] for r in R) + " |", "|---|" + "---|" * len(R)]
        for r in R:
            v = (agg.get(r) or {}).get(task)
            nr_ = NOT_RUN.get(task, {}).get(r) if not (task == "phase_diagram" and ext == "assessed_pd") else None
            row["by_rendering"][r] = v if v else {"not_run": nr_ or "not run for this rendering"}
        for k in keys:
            md.append(f"| {k} | " + " | ".join(f((row['by_rendering'][r] or {}).get(k)) if "not_run" not in row["by_rendering"][r]
                                               else "n/r" for r in R) + " |")
        nr = {r: row["by_rendering"][r]["not_run"] for r in R if "not_run" in row["by_rendering"][r]}
        if nr:
            md.append("")
            for r, why in nr.items():
                md.append(f"- n/r {RN[r]}: {why}")
        md.append("")
        res["tasks"].append(row)
    md += ["## Oracle self-test", "", "The truth written back in extractor format scores 1.0 on every precision/recall "
           "metric (boundary distances ≈ 0), on every rendering:", ""]
    for r in R:
        o = oracle.get(r, {})
        md.append(f"- {RN[r]}: tables cell_exact {f(o.get('tables', {}).get('cell_exact'))}, xy point_recall "
                  f"{f(o.get('xy', {}).get('point_recall@0.01'))}, boundary recall {f(o.get('phase_diagram', {}).get('boundary_recall@0.01'))}, "
                  f"field recall {f(o.get('phase_diagram', {}).get('field_recall'))}, text recall {f(o.get('text', {}).get('recall'))}")
    md += ["", "## Extractors that could not run", "",
           "- `thermo_extractor.raster.*` (extract_pdf_figure_panels, detect_binary_axes, extract_binary_topology, "
           "compare_binary_topology): OpenCV not installed (`require_vision`).",
           "- `thermo_extractor.proposals.multipanel_markers` (raster marker template matching): OpenCV.",
           "- `thermo_extractor.tables.ocr` (ocr_table_cells): OpenCV.",
           "- `thermo_extractor.tables.extraction` (extract_assessment_table, the Camelot route): Camelot not installed; "
           "pdfplumber's table finder used instead.", ""]
    md += ["## Tool status notes", ""]
    for ext in ("vector_route", "assessed_pd"):
        counts = {}
        for fp in sorted((B / "outputs" / ext).glob("*/*.json")):
            if fp.name == "scores.json":
                continue
            st = load_json(fp).get("status", {})
            for k, v in st.items():
                items = v if isinstance(v, list) else [v]
                for it in items:
                    if isinstance(it, dict):
                        for key in ("calibration", "manifest", "vector_markers", "error"):
                            if key in it:
                                msg = str(it[key])[:75] if key != "vector_markers" else str(it[key]).split(" (")[0]
                                counts[(fp.parent.name, k, key, msg)] = counts.get((fp.parent.name, k, key, msg), 0) + 1
        res["extractor_status"][ext] = [{"rendering": a, "task": b, "stage": c, "outcome": d, "count": n}
                                        for (a, b, c, d), n in sorted(counts.items())]
        md.append(f"### {ext}")
        md.append("")
        for (a, b, c, d), n in sorted(counts.items()):
            md.append(f"- {RN.get(a, a)} / {b} / {c}: {d} — {n}")
        md.append("")
    write_json(B / "results" / "results.json", res, pretty=True)
    (B / "results" / "RESULTS.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
