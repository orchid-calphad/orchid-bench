def main(argv=None):
    """Command-line entry point: generate the synthetic benchmark documents."""
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seed", type=int, default=20261022)
    ap.add_argument("--systems", nargs="*", help="TDB stems (default: all benchmark systems)")
    ap.add_argument("--n", type=int, default=1, help="style variants per system")
    ap.add_argument("--jobs", type=int, default=1)
    a = ap.parse_args(argv)
    stems = a.systems or [s[0] for s in system_specs]
    jobs = [(s, v) for s in stems for v in range(a.n)]
    if a.jobs > 1:
        from multiprocessing import Pool
        with Pool(a.jobs) as pool:
            res = pool.starmap(_one, [(s, v, a.seed) for s, v in jobs])
    else:
        res = [_one(s, v, a.seed) for s, v in jobs]
    manifest = {"seed": a.seed, "documents": sorted(res, key=lambda r_: r_["doc_id"])}
    write_json(docs_dir / "MANIFEST.json", manifest, pretty=True)
    print(f"{len(res)} documents")


def _one(stem, v, seed):
    doc_id, truth = build_document(stem, v, seed)
    print(doc_id, truth["renderings"]["vector"]["pages"], "pages", flush=True)
    return {"doc_id": doc_id, "pages": truth["renderings"]["vector"]["pages"], "system": truth["system"],
            "truth": f"truth/{doc_id}.json", "truth_sha256": sha256_file(truth_dir / f"{doc_id}.json")}


if __name__ == "__main__":
    main()
