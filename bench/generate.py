def invariant_table(data, style, xunit, tunit):
    B = data["elements"][1]
    rows = []
    cvals = []
    for inv in data["invariants"]:
        T = inv["T"] - 273.15 if tunit == "°C" else inv["T"]
        order = inv["reactants"] + inv["products"]
        pmap = {p["phase"]: p for p in inv["points"]}
        comps = [pmap[p]["x"] for p in order]
        cfmt = [(fmt(100 * x, 1) if xunit == "at.%" else fmt(x, 3)) for x in comps]
        rows.append([inv["reaction"], inv["type"], fmt(T, 1)] + cfmt)
        cvals.append(comps)
    xu = f"at.% {B}" if xunit == "at.%" else f"x({B})"
    if style["merged_header"]:
        header = [[{"text": "Reaction"}, {"text": "Type"}, {"text": f"T / {tunit}"},
                   {"text": f"Compositions ({xu})", "colspan": 3}],
                  [{"text": ""}, {"text": ""}, {"text": ""}, {"text": "phase 1"}, {"text": "phase 2"}, {"text": "phase 3"}]]
    else:
        header = [[{"text": "Reaction"}, {"text": "Type"}, {"text": f"T ({tunit})"},
                   {"text": f"{xu}, 1"}, {"text": f"{xu}, 2"}, {"text": f"{xu}, 3"}]]
    notes = []
    if style["footnotes"]:
        notes.append("Phases 1–3 in the order written in the reaction. Calculated with pycalphad 0.11.2 from the "
                     "SGTE dataset; synthetic document.")
    units = [None, None, tunit, xunit, xunit, xunit]
    return {"id": "invariants", "header": header, "rows": rows, "align": ["l", "l", "r", "r", "r", "r"],
            "footnotes": notes, "column_units": units}


def liquidus_table(data, style, xunit, tunit):
    """For systems without invariants: liquidus/solidus temperatures at selected compositions."""
    B = data["elements"][1]
    rows = []
    for x0 in (0.2, 0.4, 0.6, 0.8):
        Tl = Ts = None
        for rg in data["boundaries"]:
            phs = [base(c["phase"]) for c in rg["curves"]]
            if "LIQUID" not in phs or len(set(phs)) != 2:
                continue
            for c in rg["curves"]:
                x, T = np.asarray(c["x"]), np.asarray(c["T"])
                for k in range(len(x) - 1):
                    if (x[k] - x0) * (x[k + 1] - x0) <= 0 and x[k] != x[k + 1]:
                        Tv = T[k] + (T[k + 1] - T[k]) * (x0 - x[k]) / (x[k + 1] - x[k])
                        if base(c["phase"]) == "LIQUID":
                            Tl = Tv if Tl is None else max(Tl, Tv)
                        else:
                            Ts = Tv if Ts is None else max(Ts, Tv)
        if Tl is None or Ts is None:
            continue
        cv = lambda T: T - 273.15 if tunit == "°C" else T  # noqa: E731
        rows.append([fmt(100 * x0, 0) if xunit == "at.%" else fmt(x0, 2), fmt(cv(Tl), 1), fmt(cv(Ts), 1)])
    xu = f"at.% {B}" if xunit == "at.%" else f"x({B})"
    return {"id": "liquidus", "header": [[{"text": xu}, {"text": f"T liquidus / {tunit}"}, {"text": f"T solidus / {tunit}"}]],
            "rows": rows, "align": ["r", "r", "r"], "footnotes": ["Linear interpolation of the calculated boundaries."]
            if style["footnotes"] else [], "column_units": [xunit, tunit, tunit]}


def thermo_table(data, style, rng, minus):
    P = data["properties"]
    B = data["elements"][1]
    if P.get("formation"):
        rows = []
        for c in P["formation"]:
            H = c["HM_298"] / 1000
            S = c["SM_298"]
            hs = fmt(H, 2)
            if style["uncertainty"]:
                u = [0.5, 1.0, 1.5, 2.0][int(rng.integers(4))]
                hs = f"{hs} ± {u:.1f}"
            rows.append([c["label"], fmt(100 * c["x"], 1), hs.replace("-", minus), fmt(S, 2).replace("-", minus)])
        header = [[{"text": "Phase"}, {"text": f"at.% {B}"}, {"text": "ΔfH(298 K) / kJ mol⁻¹"}, {"text": "S(298 K) / J mol⁻¹ K⁻¹"}]]
        if style["merged_header"]:
            header = [[{"text": ""}, {"text": ""}, {"text": "Calculated at 298.15 K, per mole of atoms", "colspan": 2}],
                      [{"text": "Phase"}, {"text": f"at.% {B}"}, {"text": "ΔfH / kJ mol⁻¹"}, {"text": "S / J mol⁻¹ K⁻¹"}]]
        notes = []
        if style["footnotes"]:
            notes.append("Reference: stable elements (SER) at 298.15 K." + (
                " ± values are synthetic illustration uncertainties, not data." if style["uncertainty"] else ""))
        return {"id": "formation", "header": header, "rows": rows, "align": ["l", "r", "r", "r"], "footnotes": notes,
                "column_units": [None, "at.%", "kJ/mol", "J/(mol K)"]}
    rk = P.get("rk_liquid") or []
    if rk:
        rows = []
        for q in rk:
            rows.append([f"L{q['order']}", repr(float(q["a"])).replace("-", minus),
                         repr(float(q["b"])).replace("-", minus), repr(float(q["c"])).replace("-", minus)])
        header = [[{"text": "ν"}, {"text": "a / J mol⁻¹"}, {"text": "b / J mol⁻¹ K⁻¹"}, {"text": "c / J mol⁻¹ K⁻¹"}]]
        if style["merged_header"]:
            header = [[{"text": ""}, {"text": "Liquid: L(ν) = a + b·T + c·T·ln T", "colspan": 3}],
                      [{"text": "ν"}, {"text": "a"}, {"text": "b"}, {"text": "c"}]]
        return {"id": "rk_liquid", "header": header, "rows": rows, "align": ["l", "r", "r", "r"],
                "footnotes": ["Values as printed in the TDB file."] if style["footnotes"] else [],
                "column_units": [None, "J/mol", "J/(mol K)", "J/(mol K)"]}
    return None


# ------------------------------------------------------------------------------------------------ renderings
def page_affine(scale_x, scale_y, angle_deg=0.0, size=(0, 0)):
    """2x3 matrix M mapping vector-PDF points (x, y down) to rendering coordinates: [u, v] = M @ [x, y, 1]."""
    if not angle_deg:
        return [[scale_x, 0.0, 0.0], [0.0, scale_y, 0.0]]
    t = math.radians(angle_deg)
    cx, cy = size[0] / 2, size[1] / 2
    c, s = math.cos(t), math.sin(t)
    # p' = C + R (S p - C) with R = [[c, s], [-s, c]]
    return [[c * scale_x, s * scale_y, cx - c * cx - s * cy], [-s * scale_x, c * scale_y, cy + s * cx - c * cy]]


def render_all(vector_pdf, outdir, rng):
    import pymupdf
    from PIL import Image, ImageEnhance, ImageFilter
    doc = pymupdf.open(vector_pdf)
    rend = {"vector": {"file": "vector.pdf", "sha256": sha256_file(vector_pdf), "pages": doc.page_count,
                       "units": "pt", "page_size_pt": [doc[0].rect.width, doc[0].rect.height],
                       "transforms": [page_affine(1, 1) for _ in range(doc.page_count)],
                       "text_layer": True}}
    clean_files, deg_files, deg_tr, angles = [], [], [], []
    (outdir / "clean").mkdir(exist_ok=True)
    (outdir / "degraded").mkdir(exist_ok=True)
    clean_tr = []
    for i, page in enumerate(doc):
        pm = page.get_pixmap(dpi=300, alpha=False)
        fn = outdir / "clean" / f"page-{i + 1}.png"
        pm.save(str(fn))
        clean_files.append({"file": f"clean/page-{i + 1}.png", "sha256": sha256_file(fn), "size_px": [pm.width, pm.height]})
        clean_tr.append(page_affine(pm.width / page.rect.width, pm.height / page.rect.height))
        pm2 = page.get_pixmap(dpi=150, alpha=False)
        im = Image.frombytes("RGB", (pm2.width, pm2.height), pm2.samples)
        ang = float(np.round(rng.uniform(-1.0, 1.0), 3))
        gray = bool(rng.random() < 0.5)
        im = ImageEnhance.Contrast(im).enhance(float(rng.uniform(0.72, 0.88)))
        im = ImageEnhance.Brightness(im).enhance(float(rng.uniform(0.95, 1.03)))
        im = im.filter(ImageFilter.GaussianBlur(radius=float(rng.uniform(0.5, 0.9))))
        im = im.rotate(ang, resample=Image.BICUBIC, expand=False, fillcolor=(246, 245, 240))
        arr = np.asarray(im).copy()
        dens = float(rng.uniform(0.0008, 0.0025))
        m = rng.random(arr.shape[:2])
        arr[m < dens / 2] = 0
        arr[(m >= dens / 2) & (m < dens)] = 255
        im = Image.fromarray(arr)
        if gray:
            im = im.convert("L")
        q = int(rng.integers(30, 55))
        fn2 = outdir / "degraded" / f"page-{i + 1}.jpg"
        buf = io.BytesIO()
        im.save(buf, format="JPEG", quality=q, optimize=False)
        fn2.write_bytes(buf.getvalue())
        deg_files.append({"file": f"degraded/page-{i + 1}.jpg", "sha256": sha256_file(fn2), "size_px": [im.width, im.height],
                          "rotation_deg": ang, "jpeg_quality": q, "grayscale": gray, "salt_pepper_density": round(dens, 5)})
        deg_tr.append(page_affine(pm2.width / page.rect.width, pm2.height / page.rect.height, ang, (pm2.width, pm2.height)))
        angles.append(ang)
    rend["clean_raster"] = {"files": clean_files, "dpi": 300, "units": "px", "transforms": clean_tr, "text_layer": False}
    rend["degraded_raster"] = {"files": deg_files, "dpi": 150, "units": "px", "transforms": deg_tr, "text_layer": False,
                               "degradation": "contrast loss, brightness shift, Gaussian blur, rotation about the page "
                                              "centre (PIL, counter-clockwise positive), salt-and-pepper noise, JPEG"}
    # image-only PDF wrapping the degraded raster
    out = pymupdf.open()
    io_tr = []
    for i, page in enumerate(doc):
        p2 = out.new_page(width=page.rect.width, height=page.rect.height)
        p2.insert_image(p2.rect, filename=str(outdir / "degraded" / f"page-{i + 1}.jpg"))
        w, h = deg_files[i]["size_px"]
        sx, sy = page.rect.width / w, page.rect.height / h
        M = deg_tr[i]
        io_tr.append([[M[0][0] * sx, M[0][1] * sx, M[0][2] * sx], [M[1][0] * sy, M[1][1] * sy, M[1][2] * sy]])
    out.set_metadata({"producer": "PyMuPDF", "creator": "orchid-pipeline-bench", "creationDate": "", "modDate": ""})
    out.save(str(outdir / "image_only.pdf"), garbage=3, deflate=True, no_new_id=True)
    out.close()
    rend["image_only_pdf"] = {"file": "image_only.pdf", "sha256": sha256_file(outdir / "image_only.pdf"),
                              "units": "pt", "transforms": io_tr, "text_layer": False,
                              "note": "each page is the degraded raster placed full-page; no text layer"}
    doc.close()
    return rend


def apply(M, x, y):
    return [round(M[0][0] * x + M[0][1] * y + M[0][2], 3), round(M[1][0] * x + M[1][1] * y + M[1][2], 3)]


def rect_in_renderings(page, bbox, rend):
    out = {}
    for key, rr in rend.items():
        M = rr["transforms"][page]
        x0, y0, x1, y1 = bbox
        out[key] = [apply(M, x0, y0), apply(M, x1, y0), apply(M, x1, y1), apply(M, x0, y1)]
    return out


