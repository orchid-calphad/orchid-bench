# ------------------------------------------------------------------------------------------------ value formatting
class Values:
    """Collects every number stated in running text (or captions) together with its printed string."""

    def __init__(self, B):
        self.B = B
        self.items = []

    def T(self, T_K, unit, nd, quantity, ref=None):
        v = T_K - 273.15 if unit == "°C" else T_K
        s = fmt(v, nd)
        printed = f"{s} {unit}" if unit == "K" else f"{s} °C"
        return self._add(printed, float(s), unit, quantity, T_K, ref)

    def X(self, x, unit, quantity, ref=None, style=0):
        if unit == "at.%":
            s = fmt(100 * x, 1)
            printed = f"{s} at.% {self.B}" if style == 0 else f"{s} at.%"
            return self._add(printed, float(s), "at.%", quantity, x, ref)
        s = fmt(x, 3)
        printed = f"x({self.B}) = {s}" if style == 0 else f"a mole fraction of {s}"
        return self._add(printed, float(s), "mole_fraction", quantity, x, ref)

    def E(self, J, unit, nd, quantity, ref=None):
        v = J / 1000 if unit == "kJ/mol" else J
        s = fmt(v, nd)
        printed = f"{s.replace('-', '−')} {unit}"
        return self._add(printed, float(s), unit, quantity, J, ref)

    def _add(self, printed, value, unit, quantity, exact, ref):
        self.items.append({"printed": printed, "value": value, "unit": unit, "quantity": quantity,
                           "exact_SI": exact, "ref": ref})
        return printed, len(self.items) - 1


TYPE_ARTICLE = {"eutectic": "a", "eutectoid": "a", "peritectic": "a", "peritectoid": "a", "monotectic": "a",
                "syntectic": "a", "metatectic": "a", "monotectoid": "a", "unknown": "an"}


def invariant_sentences(rng, data, vals, tunit, xunit, ndT):
    out = []
    for i, inv in enumerate(data["invariants"]):
        T, ref = inv["T"], f"invariant:{i}"
        pts = inv["points"]
        mid = pts[1]
        liq = [p for p in pts if base(p["phase"]) == "LIQUID"]
        key = liq[0] if (liq and inv["type"] in ("eutectic", "peritectic", "monotectic", "metatectic")) else mid
        form = int(rng.integers(5))
        ts, ti = vals.T(T, tunit, ndT, "invariant_temperature", ref)
        xs, xi = vals.X(key["x"], xunit, f"invariant_composition:{key['label']}", ref, style=int(rng.integers(2)))
        r_ = inv["reaction"]
        typ = inv["type"]
        if form == 0:
            s = f"The {typ} reaction {r_} is calculated at {ts}, with {key['label']} at {xs}."
        elif form == 1:
            s = f"At {ts} the {typ} {r_} takes place; the {key['label']} phase then contains {xs}."
        elif form == 2:
            s = f"We obtain {ts} for the {typ} reaction ({r_}), where {key['label']} has {xs}."
        elif form == 3:
            s = f"{typ.capitalize()} equilibrium {r_} is found at {ts} and {xs} ({key['label']})."
        else:
            s = f"The dataset places {TYPE_ARTICLE.get(typ, 'a')} {typ} ({r_}) at {ts}; the composition of {key['label']} is {xs}."
        out.append((s, [ti, xi]))
    return out


def tm_sentences(rng, data, vals, tunit, ndT):
    out = []
    for side, Tm in (("A", data["Tm_A"]), ("B", data["Tm_B"])):
        if Tm is None:
            continue
        e = data["elements"][0 if side == "A" else 1]
        ts, ti = vals.T(Tm, tunit, ndT, f"melting_point:{e}", f"melting:{e}")
        s = [f"Pure {e} melts at {ts}.", f"The melting point of {e} reproduced by the dataset is {ts}.",
             f"For {e}, the liquidus meets the axis at {ts}."][int(rng.integers(3))]
        out.append((s, [ti]))
    return out


